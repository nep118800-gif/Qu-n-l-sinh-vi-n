USE QuanLySinhVien;
GO

IF OBJECT_ID('FK_LOP_LopTruong') IS NOT NULL
    ALTER TABLE LOP DROP CONSTRAINT FK_LOP_LopTruong;
DROP TABLE IF EXISTS KETQUA;
DROP TABLE IF EXISTS SINHVIEN;
DROP TABLE IF EXISTS LOP;
DROP TABLE IF EXISTS MONHOC;
DROP TABLE IF EXISTS KHOA;
GO

CREATE TABLE KHOA (
    MaKhoa  CHAR(10)      PRIMARY KEY,
    TenKhoa NVARCHAR(100) NOT NULL
);

CREATE TABLE LOP (
    MaLop       CHAR(10)      PRIMARY KEY,
    TenLop      NVARCHAR(100) NOT NULL,
    MaKhoa      CHAR(10)      NOT NULL,
    MaLopTruong CHAR(10)      NULL,   
    FOREIGN KEY (MaKhoa) REFERENCES KHOA(MaKhoa)
);

CREATE TABLE SINHVIEN (
    MaSV     CHAR(10)      PRIMARY KEY,
    HoTen    NVARCHAR(100) NOT NULL,
    NgaySinh DATE,
    GioiTinh NVARCHAR(3)   CHECK (GioiTinh IN (N'Nam', N'Nữ')),
    DiaChi   NVARCHAR(200),
    MaLop    CHAR(10)      NOT NULL,
    FOREIGN KEY (MaLop) REFERENCES LOP(MaLop)
);

ALTER TABLE LOP
ADD CONSTRAINT FK_LOP_LopTruong
FOREIGN KEY (MaLopTruong) REFERENCES SINHVIEN(MaSV);

CREATE UNIQUE INDEX UQ_LOP_LopTruong
ON LOP(MaLopTruong) WHERE MaLopTruong IS NOT NULL;

CREATE TABLE MONHOC (
    MaMH     CHAR(10)      PRIMARY KEY,
    TenMH    NVARCHAR(100) NOT NULL,
    SoTinChi INT           CHECK (SoTinChi > 0)
);

CREATE TABLE KETQUA (
    MaSV CHAR(10),
    MaMH CHAR(10),
    Diem FLOAT CHECK (Diem BETWEEN 0 AND 10),
    PRIMARY KEY (MaSV, MaMH),
    FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    FOREIGN KEY (MaMH) REFERENCES MONHOC(MaMH)
);
GO